export const LIVE_RECOVERY_ROLE = 'sol_token_executor_live_recovery';
export const LIVE_RECOVERY_SCHEMA = 'public';

export interface LiveRecoveryTableAuthority {
  readonly name: string;
  readonly select: readonly string[];
  readonly insert: readonly string[];
  readonly update: readonly string[];
}

export interface LiveRecoverySequenceAuthority {
  readonly name: string;
  readonly privileges: readonly ['USAGE'];
}

export interface LiveRecoveryDatabaseAuthority {
  readonly role: typeof LIVE_RECOVERY_ROLE;
  readonly schema: typeof LIVE_RECOVERY_SCHEMA;
  readonly tables: readonly LiveRecoveryTableAuthority[];
  readonly sequences: readonly LiveRecoverySequenceAuthority[];
}

function columns<const T extends readonly string[]>(...values: T): Readonly<T> {
  return Object.freeze(values);
}

function table(
  name: string,
  select: readonly string[],
  insert: readonly string[],
  update: readonly string[],
): LiveRecoveryTableAuthority {
  return Object.freeze({ name, select, insert, update });
}

